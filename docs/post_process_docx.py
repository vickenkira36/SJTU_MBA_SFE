"""
Post-process docx files generated by pandoc to fix table rendering issues.

Apply five fixes to all tables:
1. Width = 100% of page — table fills page width instead of being shrunk to content min-width.
2. AutoFit layout — Word allocates the 100% width across columns based on content proportions.
3. Full grid borders — every cell has top/bottom/left/right borders (matches academic-thesis style).
4. cantSplit on each row — prevent a row's content from being split across pages.
5. tblHeader on first row — repeat the header row on every page when a table spans pages.

Usage:
    python3 docs/post_process_docx.py docs/chapter04.docx [docs/chapterXX.docx ...]
"""

import os
import sys
from docx import Document
from docx.shared import Cm
from docx.oxml.ns import qn
from docx.oxml import OxmlElement


def _ensure_tbl_pr(tbl) -> object:
    tblPr = tbl.find(qn('w:tblPr'))
    if tblPr is None:
        tblPr = OxmlElement('w:tblPr')
        tbl.insert(0, tblPr)
    return tblPr


def _set_table_width_full_page(tblPr) -> None:
    """Set table width to 100% of page width (pct type, w=5000 means 100%)."""
    tblW = tblPr.find(qn('w:tblW'))
    if tblW is None:
        tblW = OxmlElement('w:tblW')
        tblPr.append(tblW)
    tblW.set(qn('w:type'), 'pct')
    tblW.set(qn('w:w'), '5000')  # 5000 = 100% (pct unit is 50ths of a percent)


def _set_autofit_layout(tblPr) -> None:
    """Use autofit layout so columns share the 100% width by content proportion."""
    tblLayout = tblPr.find(qn('w:tblLayout'))
    if tblLayout is None:
        tblLayout = OxmlElement('w:tblLayout')
        tblPr.append(tblLayout)
    tblLayout.set(qn('w:type'), 'autofit')


def _set_full_grid_borders(tblPr) -> None:
    """Apply single black border to all six edges (outer 4 + insideH + insideV)."""
    existing = tblPr.find(qn('w:tblBorders'))
    if existing is not None:
        tblPr.remove(existing)
    tblBorders = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        elem = OxmlElement(f'w:{edge}')
        elem.set(qn('w:val'), 'single')
        elem.set(qn('w:sz'), '4')         # 1/2 pt (sz unit is 1/8 pt)
        elem.set(qn('w:color'), '000000')
        elem.set(qn('w:space'), '0')
        tblBorders.append(elem)
    tblPr.append(tblBorders)


def _clear_cell_widths(table) -> None:
    """Clear per-cell fixed widths so autofit can reflow."""
    for row in table.rows:
        for cell in row.cells:
            tcPr = cell._element.find(qn('w:tcPr'))
            if tcPr is not None:
                tcW = tcPr.find(qn('w:tcW'))
                if tcW is not None:
                    tcW.set(qn('w:type'), 'auto')
                    tcW.set(qn('w:w'), '0')


def _set_row_properties(table) -> None:
    """cantSplit on every row + tblHeader on the first row."""
    for row_idx, row in enumerate(table.rows):
        trPr = row._element.find(qn('w:trPr'))
        if trPr is None:
            trPr = OxmlElement('w:trPr')
            row._element.insert(0, trPr)
        if trPr.find(qn('w:cantSplit')) is None:
            trPr.append(OxmlElement('w:cantSplit'))
        if row_idx == 0 and trPr.find(qn('w:tblHeader')) is None:
            trPr.append(OxmlElement('w:tblHeader'))


def _clear_cell_first_line_indent(table) -> None:
    """
    Remove first-line indent from every paragraph inside every cell.

    The thesis body style applies a 2-character first-line indent (anti-required by
    the AGENTS.md formatting spec), which is correct for body paragraphs but wrong
    for table cells — it makes the first line of each cell offset by one character,
    misaligning visually-stacked content. We strip it here.
    """
    for row in table.rows:
        for cell in row.cells:
            for para in cell.paragraphs:
                pPr = para._element.find(qn('w:pPr'))
                if pPr is None:
                    pPr = OxmlElement('w:pPr')
                    para._element.insert(0, pPr)
                ind = pPr.find(qn('w:ind'))
                if ind is None:
                    ind = OxmlElement('w:ind')
                    pPr.append(ind)
                # Force zero first-line indent and zero hanging indent
                ind.set(qn('w:firstLine'), '0')
                ind.set(qn('w:firstLineChars'), '0')
                # Also zero out any hanging indent that may have been inherited
                if ind.get(qn('w:hanging')) is not None:
                    ind.set(qn('w:hanging'), '0')


def _make_para(text, *, size_pt, bold=False, align='center', font_cjk='黑体',
               space_before_pt=0, space_after_pt=0, underline=False):
    """Build a standalone <w:p> with a single styled run (or empty if text is '')."""
    p = OxmlElement('w:p')
    pPr = OxmlElement('w:pPr')
    jc = OxmlElement('w:jc'); jc.set(qn('w:val'), align); pPr.append(jc)
    spacing = OxmlElement('w:spacing')
    spacing.set(qn('w:before'), str(int(space_before_pt * 20)))
    spacing.set(qn('w:after'), str(int(space_after_pt * 20)))
    spacing.set(qn('w:line'), '360'); spacing.set(qn('w:lineRule'), 'auto')
    pPr.append(spacing)
    ind = OxmlElement('w:ind')
    ind.set(qn('w:firstLine'), '0'); ind.set(qn('w:firstLineChars'), '0')
    pPr.append(ind)
    p.append(pPr)
    if text:
        r = OxmlElement('w:r')
        rPr = OxmlElement('w:rPr')
        rfonts = OxmlElement('w:rFonts')
        rfonts.set(qn('w:ascii'), 'Times New Roman')
        rfonts.set(qn('w:hAnsi'), 'Times New Roman')
        rfonts.set(qn('w:eastAsia'), font_cjk)
        rPr.append(rfonts)
        if bold:
            rPr.append(OxmlElement('w:b')); rPr.append(OxmlElement('w:bCs'))
        if underline:
            u = OxmlElement('w:u'); u.set(qn('w:val'), 'single'); rPr.append(u)
        sz = OxmlElement('w:sz'); sz.set(qn('w:val'), str(int(size_pt * 2)))
        szCs = OxmlElement('w:szCs'); szCs.set(qn('w:val'), str(int(size_pt * 2)))
        rPr.append(sz); rPr.append(szCs)
        r.append(rPr)
        t = OxmlElement('w:t'); t.set(qn('xml:space'), 'preserve'); t.text = text
        r.append(t)
        p.append(r)
    return p


def _make_field_row(label, value):
    """Cover field line: '标签：____value____' centered, value underlined."""
    p = OxmlElement('w:p')
    pPr = OxmlElement('w:pPr')
    jc = OxmlElement('w:jc'); jc.set(qn('w:val'), 'center'); pPr.append(jc)
    spacing = OxmlElement('w:spacing')
    spacing.set(qn('w:after'), '160'); spacing.set(qn('w:line'), '300')
    spacing.set(qn('w:lineRule'), 'auto'); pPr.append(spacing)
    p.append(pPr)
    for txt, ul in ((label + '：', False), (value, True)):
        r = OxmlElement('w:r')
        rPr = OxmlElement('w:rPr')
        rfonts = OxmlElement('w:rFonts')
        rfonts.set(qn('w:ascii'), 'Times New Roman')
        rfonts.set(qn('w:hAnsi'), 'Times New Roman')
        rfonts.set(qn('w:eastAsia'), '黑体')
        rPr.append(rfonts)
        if ul:
            u = OxmlElement('w:u'); u.set(qn('w:val'), 'single'); rPr.append(u)
        sz = OxmlElement('w:sz'); sz.set(qn('w:val'), '28')
        szCs = OxmlElement('w:szCs'); szCs.set(qn('w:val'), '28')
        rPr.append(sz); rPr.append(szCs)
        r.append(rPr)
        t = OxmlElement('w:t'); t.set(qn('xml:space'), 'preserve'); t.text = txt
        r.append(t)
        p.append(r)
    return p


def _make_logo_para(doc, img_path, width_cm=3.6, space_after_pt=12):
    """居中插入校徽图片，返回该段落的 <w:p>。"""
    # 借助一个临时段落让 python-docx 完成图片嵌入与关系注册
    tmp = doc.add_paragraph()
    run = tmp.add_run()
    run.add_picture(img_path, width=Cm(width_cm))
    p_el = tmp._element
    p_el.getparent().remove(p_el)  # 从文档末尾摘出，稍后插到封面
    # 居中
    pPr = p_el.get_or_add_pPr()
    jc = OxmlElement('w:jc'); jc.set(qn('w:val'), 'center'); pPr.append(jc)
    spacing = OxmlElement('w:spacing')
    spacing.set(qn('w:after'), str(int(space_after_pt * 20))); pPr.append(spacing)
    return p_el


def _make_page_break():
    p = OxmlElement('w:p')
    r = OxmlElement('w:r')
    br = OxmlElement('w:br'); br.set(qn('w:type'), 'page')
    r.append(br)
    p.append(r)
    return p


def _base_sectpr_xml(extra=''):
    """生成一个完整的 sectPr XML 字符串（继承模板页面设置 + 页眉页脚引用占位）。

    sectPr 必须包含页面尺寸/边距，否则 Word 会回退到默认 A4 边距。
    extra 用于追加 titlePg / pgNumType 等差异化设置。
    """
    return (
        '<w:sectPr xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        '<w:pgSz w:w="11906" w:h="16838"/>'
        '<w:pgMar w:top="1985" w:right="1418" w:bottom="2268" w:left="1418" '
        'w:header="1418" w:footer="1701" w:gutter="0"/>'
        f'{extra}'
        '</w:sectPr>'
    )


def _make_section_para(sectpr_xml):
    """生成一个仅承载节属性的空段落（OOXML：节属性写在该节末段的 pPr 内）。"""
    from docx.oxml import parse_xml
    p = OxmlElement('w:p')
    pPr = OxmlElement('w:pPr')
    pPr.append(parse_xml(sectpr_xml))
    p.append(pPr)
    return p



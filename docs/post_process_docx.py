def _load_meta():
    import json
    meta = dict(_DEFAULT_META)
    if os.path.exists(_META_PATH):
        with open(_META_PATH, encoding='utf-8') as f:
            data = json.load(f)
        meta.update({k: v for k, v in data.items() if not k.startswith('_')})
    return meta


